"""Generate THIRD_PARTY_NOTICES.md from `cargo metadata` (MASTER_PLAN §11.1).

Collects each non-workspace dependency's declared licence and the licence /
notice files shipped in its source package. Deterministic: output is sorted.
Usage: python tools/third_party_notices.py [--check]
"""
import json
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "THIRD_PARTY_NOTICES.md"
LICENSE_PREFIXES = ("license", "licence", "copying", "notice", "unlicense")


def main() -> int:
    meta = json.loads(subprocess.check_output(
        ["cargo", "metadata", "--format-version", "1", "--locked", "--filter-platform", "x86_64-pc-windows-msvc"],
        cwd=ROOT / "engine"))
    workspace = set(meta["workspace_members"])
    resolved = {n["id"] for n in meta["resolve"]["nodes"]}
    lines = ["# Third-party notices", "",
             "TreeDock includes the following third-party components. Each remains under its own licence.",
             "Generated by `tools/third_party_notices.py`; do not edit by hand.", ""]
    for p in sorted(meta["packages"], key=lambda p: (p["name"], p["version"])):
        if p["id"] in workspace or p["id"] not in resolved:
            continue
        lines += [f"## {p['name']} {p['version']}", "", f"License: `{p.get('license') or 'see files'}`", ""]
        pkg_dir = pathlib.Path(p["manifest_path"]).parent
        files = sorted(f for f in pkg_dir.iterdir() if f.is_file() and f.name.lower().startswith(LICENSE_PREFIXES))
        if not files:
            lines += ["_No licence file shipped in the package; see the declared licence above._", ""]
        for f in files:
            text = f.read_text(encoding="utf-8", errors="replace").strip()
            lines += [f"<details><summary>{f.name}</summary>", "", "```text", text, "```", "", "</details>", ""]
    content = "\n".join(lines) + "\n"
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != content:
            print("THIRD_PARTY_NOTICES.md is out of date", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(content, encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
